"""Write report.md from schools.json and <cache_dir>/review.json.

    python -I report.py <cache_dir>

The hand-written findings (REVIEW_NOTES) are edited per run after a human/agent pass.
"""
import collections, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from report_notes import REVIEW_NOTES, SCHEDULE_NOTES  # noqa: E402


def main():
    cache = sys.argv[1]
    rows = json.load(open(os.path.join(HERE, "schools.json"), encoding="utf-8"))
    rv = json.load(open(os.path.join(cache, "review.json")))
    lv = collections.Counter(r["level"] for r in rows)
    st = collections.Counter((r["level"], (r["hudl"] or {}).get("status", "none")) for r in rows)
    yt = collections.Counter((r["level"], bool(r["youtube"])) for r in rows)
    yts = collections.Counter(r["level"] for r in rows if r["youtubeStreamsBasketball"])
    site = collections.Counter(r["level"] for r in rows if r["athleticsSite"])
    L = []
    w = L.append
    w("# College basketball directory: Union Adventist opponents and their opponents\n")
    w("Built %s from official athletics-site schedules for %s. Generated by `scrape.py` + `build.py` + `report.py`.\n"
      % (__import__("datetime").date.today().isoformat(), " and ".join(__import__("config").SEASONS)))
    w("## Counts\n")
    w("| | Level 0 (Union) | Level 1 | Level 2 | Total |")
    w("|---|---|---|---|---|")
    def line(label, f):
        vals = [f(l) for l in (0, 1, 2)]
        w("| %s | %s | %s | %s | %s |" % (label, *vals, sum(vals)))
    line("Schools", lambda l: lv[l])
    line("Hudl: active (broadcast in last 12 months)", lambda l: st[(l, "active")])
    line("Hudl: stale (site exists, older broadcasts only)", lambda l: st[(l, "stale")])
    line("Hudl: none (no matching site, or site with no archived broadcasts)", lambda l: st[(l, "none")])
    line("YouTube channel found", lambda l: yt[(l, True)])
    line("YouTube: schedule links show basketball streamed on YouTube", lambda l: yts[l])
    line("Athletics site identified", lambda l: site[l])
    w("")
    w("Hudl 'none' includes schools with no Hudl site at all (`hudl: null`) and schools whose only matching site has no archived broadcasts.\n")
    w("## Level-1 schedules\n")
    w("| School | Sport | Season | Games | Note |")
    w("|---|---|---|---|---|")
    for l in rv["log"]:
        w("| %s | %s | %s | %s | %s |" % (l["school"], l["sport"], l["season"], l["games"], l["note"]))
    w("")
    for n in SCHEDULE_NOTES:
        w("- " + n)
    w("")
    w("## Ambiguous Hudl matches (several candidate sites with broadcasts)\n")
    for n, h in sorted(rv["hudl"].items()):
        if h["note"]:
            w("- **%s**: %s" % (n, h["note"]))
    w("")
    w("## Name merges and guesses to check\n")
    for n, t in rv["notes"].items():
        w("- **%s**: %s" % (n, t))
    w("")
    if rv["unmapped"]:
        w("## Unmapped opponent names (not in the directory)\n")
        for name, school, c in rv["unmapped"]:
            w("- `%s` on %s (%d)" % (name, school, c))
        w("")
    w("## Dropped schedule entries (events, placeholders, non-college)\n")
    w(", ".join("`%s`" % k for k in sorted(rv["dropped"]) if k)+ "\n")
    w("## Needs a human eye\n")
    for n in REVIEW_NOTES:
        w("- " + n)
    w("")
    open(os.path.join(HERE, "report.md"), "w", encoding="utf-8").write("\n".join(L))


if __name__ == "__main__":
    main()
